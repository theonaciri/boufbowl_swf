"""Print or generate the active rulebook, including every provisional choice."""
import argparse
import json
from pathlib import Path

from backend.rulebook import rulebook_snapshot
from tools.game_config import ROOT, STADIUMS, load_config, resolve_stadium


def render(snapshot):
    rows=['# Boufbowl restoration rulebook', '', f"Profile: `{snapshot['id']}`. Evidence: preservation commit `{snapshot['evidence_revision']}`.",
          '',f"Policy/evidence fingerprint: `{snapshot['sha256']}`.",
          '', snapshot['target'], '', '**Provisional does not mean historically verified.** The unknown original score table and random CDF are not reconstructed.', '',
          '| Case | Rule | Status | Evidence | Decision |', '| --- | --- | --- | --- | --- |']
    for rule in snapshot['rules']:
        rows.append(f"| {rule['id']} | {rule['name']} | {rule['status']} | {', '.join(rule['sources'])} | {rule.get('decision','See reconstruction choices below.')} |")
    power_note = ('Values follow the preserved original client tooltips. Mask numbers and exceptional inversion/stacking cases remain provisional.'
                  if any(a.get('verified') for a in snapshot['class_abilities'].values())
                  else 'These retain the requested custom profile; they are not a recovered historical spell table.')
    rows.extend(['','## Configured class effects','',power_note,'',
                 '| Class | Configured effect | Historically verified |','| --- | --- | --- |'])
    for name,ability in snapshot['class_abilities'].items():
        effect={key:value for key,value in ability.items() if key not in ('name','verified')}
        rows.append(f"| {name} | `{json.dumps(effect,sort_keys=True)}` | {'yes' if ability.get('verified') else 'no'} |")
    rows.extend(['','## Configured attributes','','Roles follow the recovered composition rule; numeric balance is not certified as the original table.','',
                 '| Class | Role | Earth | Fire | Air | Water | HP | Regeneration interval |','| --- | --- | --- | --- | --- | --- | --- | --- |'])
    for name,override in snapshot['class_attributes']['overrides'].items():
        values={**snapshot['class_attributes']['defaults'],**override}
        role={1:'Blocker',2:'Dodger',3:'Runner',4:'Thrower'}[values['role']]
        rows.append(f"| {name} | {role} | "+' | '.join(str(values[key]) for key in ('earth','fire','air','water','health','regeneration'))+' |')
    rows.extend(['','## Match configuration','','```json',json.dumps(snapshot['match_policy'],indent=2),'```','',
                 'Use `--stadium KARA` (or another configured stadium) to print its resolved match/ability policy.',
                 '','## Active reconstruction policy','','These values are configurable replacement balance, not recovered historical constants.','',
                 '```json',json.dumps(snapshot['policy'],indent=2),'```','','## Still unresolved',''])
    rows.extend('- '+question for question in snapshot['unresolved'])
    rows.extend(['','See [reconstruction choices](RULEBOOK_CHOICES.md) for formulas, boundaries, scope and compatibility.',
                 'See [original audit](RECOVERED_RULES.md) for provenance and the previous implementation baseline.', '',
                 'Generated by `python3 -m tools.rulebook --write docs/RULEBOOK.md` from `resources/rulebook.json` and the active configuration.',''])
    return '\n'.join(rows)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config',type=Path,default=ROOT/'resources/game_config.json')
    parser.add_argument('--json',action='store_true')
    parser.add_argument('--stadium',choices=STADIUMS)
    parser.add_argument('--write',type=Path)
    args=parser.parse_args()
    config=load_config(args.config)
    snapshot=rulebook_snapshot(resolve_stadium(config,args.stadium) if args.stadium else config['rules'])
    if snapshot is None:
        parser.error('This configuration uses the legacy simulator without an active rulebook')
    output=json.dumps(snapshot,indent=2)+'\n' if args.json else render(snapshot)
    if args.write:
        args.write.write_text(output)
        print(f'Wrote {args.write} ({len(snapshot["rules"])} rules; {snapshot["id"]})')
    else:print(output,end='')


if __name__=='__main__':main()
